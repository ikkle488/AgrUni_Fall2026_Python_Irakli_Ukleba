while True:
    try:
        a = float(input('შეიყვანეთ პირველი გვერდის სიგრძე: '))
        b = float(input('შეიყვანეთ მეორე გვერდის სიგრძე: '))
        c = float(input('შეიყვანეთ მესამე გვერდის გვერდის სიგრძე: '))
        if a > 0 and b > 0 and c > 0 and a + b > c and a + c > b and b + c > a:
            P = a+b+c
            s = (a + b + c) / 2
            A = (s*(s-a)*(s-b)*(s-c))**0.5
            print('სამკუთხედის პერიმეტრია:' + str(P) + '\n' + 'სამკუთხედის ფართობია:' + str(A))
            break
        else:
            print('გთხოვთ შეიყვანოთ გვერდების სიგრძეები დადებითი ათწილადის სახით რომლებლიც აკმაყოფილებს სამკუთხედის უტოლობას')
    except ValueError:
        print('გთხოვთ შეიყვანოთ გვერდების სიგრძეები დადებითი ათწილადის სახით, მთელი გამოყავით წერტილით')